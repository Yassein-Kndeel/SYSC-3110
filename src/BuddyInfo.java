
public class BuddyInfo {

        private String name;
        private int age;

        public BuddyInfo(String name, int age) {
            this.name = name;
            this.age = age;
        }

        public BuddyInfo(){
            name = "Unknown";
            age = 0;
        }

        public String getName() {
            return name;
        }

        public String setName(String name){
            return this.name = name;
        }





    }


